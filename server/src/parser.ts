// Document model for NASM source files: labels/constants, doc comments,
// and global/extern declarations.
export type SymbolKind = "label" | "const" | "data";

export interface DocParam {
    name: string;
    size: string;
    desc: string;
}

export interface SymbolDoc {
    brief: string[];
    params: DocParam[];
    returns: DocParam[];
}

export interface AsmSymbol {
    name: string;
    kind: SymbolKind;
    line: number;
    character: number;
    doc: SymbolDoc;
    /** Extra one-liner (data reserves: "4 bytes", "db data", ...). */
    detail?: string;
}

export interface ExternDecl {
    name: string;
    line: number;
}

export interface StrucMember {
    /** As written (usually with a leading dot). */
    name: string;
    /** Without leading dots, for filtering. */
    bare: string;
    kind: "field" | "const";
    line: number;
    character: number;
    /** Bytes per element (fields only). */
    size: number | null;
    count: number | null;
    total: number | null;
    /** Byte offset within the struc (fields only). */
    offset: number | null;
    /** Raw value text (equ consts only). */
    value: string | null;
    /** Trailing `;` comment on the member line. */
    brief: string;
}

export interface StrucDef {
    name: string;
    line: number;
    endLine: number;
    members: StrucMember[];
    totalSize: number;
}

export interface DocumentModel {
    symbols: AsmSymbol[];
    globals: string[];
    externs: ExternDecl[];
    strucs: StrucDef[];
}

/** Brief text for the auto-generated `Name_size` constant. */
export function strucSizeBrief(def: Pick<StrucDef, "name" | "totalSize">): string {
    return `Size of struc \`${def.name}\`: ${def.totalSize} bytes (auto-generated by NASM).`;
}

const LABEL_REGEX = /^\s*([A-Za-z_.$][\w.$]*)\s*:/;
const CONST_REGEX = /^\s*([A-Za-z_.$][\w.$]*)\s+equ\b/i;
const GLOBAL_DECL_REGEX = /^\s*(global|extern)\b\s*(.*)$/i;
const STRUC_REGEX = /^\s*struc\b\s*([A-Za-z_.$][\w.$]*)/i;
const ENDSTRUC_REGEX = /^\s*endstruc\b/i;
const MEMBER_RES_REGEX = /^\s*([A-Za-z_.$][\w.$]*)\s*:?\s*(res[bwdqotyxz]|d[bwdqtyz])\b\s*(.*)$/i;
const MEMBER_EQU_REGEX = /^\s*([A-Za-z_.$][\w.$]*)\s*:?\s*\bequ\b\s*(.*)$/i;
const STRUC_ALIGN_REGEX = /^\s*alignb?\s+(\d+)/i;
const STRUC_PAD_REGEX = /^\s*(res[bwdqotyxz]|d[bwdqtyz])\b\s*(.*)$/i;
const DATA_DEF_REGEX = /^\s*([A-Za-z_.$][\w.$]*)\s+(res[bwdqotyxz]|d[bwdqtyz])\b\s*(.*)$/i;
const DATA_AFTER_COLON_REGEX = /:\s*(res[bwdqotyxz]|d[bwdqtyz])\b\s*(.*)$/i;

/** One-liner for a data definition: exact bytes when countable. */
function dataDetail(op: string, rest: string): string {
    const lower = op.toLowerCase();
    const size = lower.startsWith("res") ? RES_SIZES[lower] : DB_SIZES[lower];
    const t = rest.trim();
    if (size !== undefined && lower.startsWith("res") && /^\d+$/.test(t)) {
        const n = parseInt(t, 10) * size;
        return `${n} byte${n === 1 ? "" : "s"}`;
    }
    if (size !== undefined && lower.startsWith("res")) {
        return `${lower} reserve`;
    }
    return `${lower} initialized data`;
}

/** Element count for a reservation: plain integer for resX, comma-separated
 * items for db-style initializers. */
function countReservation(op: string, rest: string): number {
    const t = rest.trim();
    if (!t) {
        return 1;
    }
    if (op.startsWith("res")) {
        const n = parseInt(t, 10);
        return isNaN(n) || n < 1 ? 1 : n;
    }
    const scrubbed = t.replace(/'(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*"|`(?:[^`\\]|\\.)*`/g, "_");
    return scrubbed.split(",").filter((p) => p.trim().length > 0).length || 1;
}

const RES_SIZES: Record<string, number> = {
    resb: 1,
    resw: 2,
    resd: 4,
    resq: 8,
    rest: 10,
    reso: 16,
    resy: 32,
    resz: 64,
};
const DB_SIZES: Record<string, number> = {
    db: 1,
    dw: 2,
    dd: 4,
    dq: 8,
    dt: 10,
    do: 16,
    dy: 32,
    dz: 64,
};

// A doc line is a `;` comment. Optional decoration (`---`, `--@`, `@`, `;;`)
// is stripped, so all of
//   ; Adds two numbers.
//   ;; Adds two numbers.
//   ;---@param eax first operand
//   ; @param ebx second operand
//   ;---@return eax the sum
// attach to the label below. A `;---...` separator or blank line ends the block.
const DOC_PREFIX_REGEX = /^\s*;\s*(?:---?\s*@|---@?|@)?\s?(.*)$/;
const SEPARATOR_REGEX = /^[-=]{3,}$/;
const PARAM_TAG_REGEX = /^param\s+(\S+)\s*(.*)$/i;
const RETURN_TAG_REGEX = /^returns?\s*(.*)$/i;

// NASM size keywords, usable before or after the name:
//   ; @return byte rax current character
//   ; @param somebuffer 192 bytes str buffer
const SIZE_KEYWORD_REGEX = /^(byte|word|dword|qword|tword|tbyte|oword|yword|zword)$/i;
const SIZE_COUNT_REGEX = /^\d+$/;
const SIZE_UNIT_REGEX = /^bytes?$/i;

export function splitComment(raw: string): { code: string; comment: string | null } {
    let quote: string | null = null;
    for (let i = 0; i < raw.length; i++) {
        const ch = raw[i];
        if (quote) {
            if (ch === quote) {
                quote = null;
            }
        } else if (ch === "'" || ch === '"' || ch === "`") {
            quote = ch;
        } else if (ch === ";") {
            return { code: raw.slice(0, i), comment: raw.slice(i + 1) };
        }
    }
    return { code: raw, comment: null };
}

function splitEntry(text: string): DocParam | null {
    const toks = text.split(/\s+/).filter((t) => t.length > 0);
    if (toks.length === 0) {
        return null;
    }
    let size = "";
    let i = 0;
    const takeSize = (): boolean => {
        if (i < toks.length && SIZE_KEYWORD_REGEX.test(toks[i])) {
            size = toks[i].toLowerCase();
            i++;
            return true;
        }
        if (i + 1 < toks.length && SIZE_COUNT_REGEX.test(toks[i]) && SIZE_UNIT_REGEX.test(toks[i + 1])) {
            size = `${toks[i]} bytes`;
            i += 2;
            return true;
        }
        return false;
    };
    takeSize();
    let name = "";
    if (i < toks.length) {
        name = toks[i].replace(/:+$/, "");
        if (/^[-:]+$/.test(name)) {
            name = "";
        }
        i++;
    }
    if (!size) {
        takeSize();
    }
    const desc = toks.slice(i).join(" ").replace(/^[-:\s]+/, "");
    return { name, size, desc };
}

function formatEntry(e: DocParam): string {
    let s = e.name ? `\`${e.name}\`` : "";
    if (e.size) {
        s += (s ? " - " : "") + e.size;
    }
    if (e.desc) {
        s += (s ? " - " : "") + e.desc;
    }
    return `- ${s}`;
}

function parseDocLine(content: string, doc: SymbolDoc): void {
    const tag = content.replace(/^@/, "").trim();
    let m = PARAM_TAG_REGEX.exec(tag);
    if (m) {
        const e = splitEntry(`${m[1] || ""} ${m[2] || ""}`);
        if (e) {
            doc.params.push(e);
        }
        return;
    }
    m = RETURN_TAG_REGEX.exec(tag);
    if (m) {
        const e = splitEntry(m[1] || "");
        if (e) {
            doc.returns.push(e);
        }
        return;
    }
    doc.brief.push(content);
}

// Collect the contiguous `;` comment block directly above `symbolLine`.
// `global`/`extern` declaration lines are transparent to the scan; blank
// lines and `;---` separators end it. `trailing` is the `;` comment on the
// symbol line itself (fallback brief).
export function extractDocComment(lines: string[], symbolLine: number, trailing: string): SymbolDoc {
    const doc: SymbolDoc = { brief: [], params: [], returns: [] };
    const block: string[] = [];
    for (let i = symbolLine - 1; i >= 0; i--) {
        const raw = lines[i];
        if (!raw.trim()) {
            break;
        }
        if (/^\s*(global|extern)\b/i.test(splitComment(raw).code)) {
            continue;
        }
        const dm = DOC_PREFIX_REGEX.exec(raw);
        if (!dm) {
            break;
        }
        // Work from the raw remainder so the `@` decoration matcher in
        // DOC_PREFIX_REGEX cannot swallow a bare `---` separator first.
        const afterSemi = raw.replace(/^\s*;\s*/, "").replace(/^;+/, "");
        if (SEPARATOR_REGEX.test(afterSemi.trim())) {
            break;
        }
        const content = afterSemi.replace(/^(?:---?\s*@|---@?|@)\s?/, "").trim();
        if (!content) {
            block.unshift("");
            continue;
        }
        block.unshift(content);
    }
    for (const line of block) {
        parseDocLine(line, doc);
    }
    if (block.length === 0 && trailing) {
        doc.brief.push(trailing);
    }
    return doc;
}

export function renderSymbolDoc(sym: Pick<AsmSymbol, "name" | "kind" | "doc"> & { detail?: string }): string {
    const lines: string[] = [];
    lines.push("```nasm");
    lines.push(sym.kind === "label" ? `${sym.name}:` : sym.name);
    lines.push("```");
    lines.push("");
    const doc = sym.doc;
    const hasDoc =
        doc && (doc.brief.some((l) => l.trim()) || doc.params.length > 0 || doc.returns.length > 0);
    if (!hasDoc && sym.kind !== "data") {
        lines.push(sym.kind === "label" ? "Code label." : "Constant defined with `equ`.");
        return lines.join("\n");
    }
    if (sym.kind === "data") {
        lines.push(sym.detail ? `Data reserve \u2014 ${sym.detail}.` : "Data reserve.");
        lines.push("");
    }
    const brief = doc.brief.join("\n").trim();
    if (brief) {
        lines.push(brief);
        lines.push("");
    }
    if (doc.params.length > 0) {
        lines.push("**Parameters**");
        lines.push("");
        for (const p of doc.params) {
            lines.push(formatEntry(p));
        }
        lines.push("");
    }
    if (doc.returns.length > 0) {
        lines.push("**Returns**");
        lines.push("");
        for (const r of doc.returns) {
            lines.push(formatEntry(r));
        }
    }
    return lines.join("\n").replace(/\n{3,}/g, "\n\n").trim();
}

export function parseDocument(text: string): DocumentModel {
    const symbols: AsmSymbol[] = [];
    const globals: string[] = [];
    const externs: ExternDecl[] = [];
    const strucs: StrucDef[] = [];
    let curStruc: { name: string; line: number; members: StrucMember[]; offset: number } | null = null;
    const closeStruc = (endLine: number): void => {
        if (!curStruc) {
            return;
        }
        strucs.push({
            name: curStruc.name,
            line: curStruc.line,
            endLine,
            members: curStruc.members,
            totalSize: curStruc.offset,
        });
        const sizeDoc: SymbolDoc = { brief: [], params: [], returns: [] };
        symbols.push({
            name: `${curStruc.name}_size`,
            kind: "const",
            line: endLine,
            character: 0,
            doc: {
                brief: [
                    strucSizeBrief({ name: curStruc.name, totalSize: curStruc.offset }),
                ],
                params: [],
                returns: [],
            },
        });
        curStruc = null;
    };
    const lines = text.split(/\r?\n/);
    for (let lineIndex = 0; lineIndex < lines.length; lineIndex++) {
        const raw = lines[lineIndex];
        const { code, comment } = splitComment(raw);
        if (!code.trim()) {
            continue;
        }
        const strucMatch = STRUC_REGEX.exec(code);
        if (strucMatch) {
            closeStruc(lineIndex);
            curStruc = { name: strucMatch[1], line: lineIndex, members: [], offset: 0 };
            continue;
        }
        if (ENDSTRUC_REGEX.test(code)) {
            closeStruc(lineIndex);
            continue;
        }
        if (curStruc) {
            const alignMatch = STRUC_ALIGN_REGEX.exec(code);
            if (alignMatch) {
                const n = parseInt(alignMatch[1], 10);
                if (!isNaN(n) && n > 0) {
                    curStruc.offset = Math.ceil(curStruc.offset / n) * n;
                }
                continue;
            }
            const member = parseStrucMember(code, comment, lineIndex, raw, curStruc.offset);
            if (member) {
                curStruc.members.push(member.member);
                curStruc.offset = member.newOffset;
                continue;
            }
            // Unnamed reservation (padding): advances the offset, adds no member.
            const padMatch = STRUC_PAD_REGEX.exec(code);
            if (padMatch) {
                const op = padMatch[1].toLowerCase();
                const size = op.startsWith("res") ? RES_SIZES[op] : DB_SIZES[op];
                if (size !== undefined) {
                    curStruc.offset += size * countReservation(op, padMatch[2] || "");
                    continue;
                }
            }
        }
        const declMatch = GLOBAL_DECL_REGEX.exec(code);
        if (declMatch) {
            const isGlobal = declMatch[1].toLowerCase() === "global";
            for (const part of declMatch[2].split(/[,\s]+/)) {
                const clean = part.split(":")[0].trim();
                if (/^[A-Za-z_.$][\w.$]*$/.test(clean)) {
                    if (isGlobal) {
                        globals.push(clean);
                    } else {
                        externs.push({ name: clean, line: lineIndex });
                    }
                }
            }
            continue;
        }
        const trailing = comment ? comment.trim() : "";
        const labelMatch = LABEL_REGEX.exec(code);
        if (labelMatch) {
            const name = labelMatch[1];
            const character = raw.indexOf(name);
            const afterColon = DATA_AFTER_COLON_REGEX.exec(code);
            if (afterColon) {
                symbols.push({
                    name,
                    kind: "data",
                    line: lineIndex,
                    character: character >= 0 ? character : 0,
                    doc: extractDocComment(lines, lineIndex, trailing),
                    detail: dataDetail(afterColon[1], afterColon[2] || ""),
                });
            } else {
                symbols.push({
                    name,
                    kind: "label",
                    line: lineIndex,
                    character: character >= 0 ? character : 0,
                    doc: extractDocComment(lines, lineIndex, trailing),
                });
            }
            continue;
        }
        const constMatch = CONST_REGEX.exec(code);
        if (constMatch) {
            const name = constMatch[1];
            const character = raw.indexOf(name);
            symbols.push({
                name,
                kind: "const",
                line: lineIndex,
                character: character >= 0 ? character : 0,
                doc: extractDocComment(lines, lineIndex, trailing),
            });
            continue;
        }
        const dataMatch = DATA_DEF_REGEX.exec(code);
        if (dataMatch) {
            const name = dataMatch[1];
            const character = raw.indexOf(name);
            symbols.push({
                name,
                kind: "data",
                line: lineIndex,
                character: character >= 0 ? character : 0,
                doc: extractDocComment(lines, lineIndex, trailing),
                detail: dataDetail(dataMatch[2], dataMatch[3] || ""),
            });
        }
    }
    closeStruc(lines.length - 1);
    return { symbols, globals, externs, strucs };
}

/** Parse one struc member line. Returns null when the line is not a member. */
function parseStrucMember(
    code: string,
    comment: string | null,
    lineIndex: number,
    raw: string,
    offset: number
): { member: StrucMember; newOffset: number } | null {
    const resMatch = MEMBER_RES_REGEX.exec(code);
    if (resMatch) {
        const name = resMatch[1];
        if (!/^[A-Za-z_.$][\w.$]*$/.test(name)) {
            return null;
        }
        const op = resMatch[2].toLowerCase();
        const size = op.startsWith("res") ? RES_SIZES[op] : DB_SIZES[op];
        if (size === undefined) {
            return null;
        }
        const rest = (resMatch[3] || "").trim();
        const count = countReservation(op, rest);
        const total = size * count;
        const character = raw.indexOf(name);
        return {
            member: {
                name,
                bare: name.replace(/^\.+/, ""),
                kind: "field",
                line: lineIndex,
                character: character >= 0 ? character : 0,
                size,
                count,
                total,
                offset,
                value: null,
                brief: (comment || "").trim(),
            },
            newOffset: offset + total,
        };
    }
    const equMatch = MEMBER_EQU_REGEX.exec(code);
    if (equMatch) {
        const name = equMatch[1];
        if (!/^[A-Za-z_.$][\w.$]*$/.test(name)) {
            return null;
        }
        const character = raw.indexOf(name);
        const value = (equMatch[2] || "").trim();
        return {
            member: {
                name,
                bare: name.replace(/^\.+/, ""),
                kind: "const",
                line: lineIndex,
                character: character >= 0 ? character : 0,
                size: null,
                count: null,
                total: null,
                offset: null,
                value: value || null,
                brief: (comment || "").trim(),
            },
            newOffset: offset,
        };
    }
    return null;
}
