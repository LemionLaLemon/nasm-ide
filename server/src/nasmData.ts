const instructionIndex = new Map<string, Instruction>();
for (const inst of instructions) {
    instructionIndex.set(inst.mnemonic.toLowerCase(), inst);
}
const registerIndex = new Map<string, NasRegister>();
for (const reg of registers) {
    registerIndex.set(reg.name.toLowerCase(), reg);
}
const directiveIndex = new Map<string, Directive>();
for (const dir of directives) {
    directiveIndex.set(dir.name.toLowerCase(), dir);
}

export function getInstruction(mnemonic: string): Instruction | undefined {
    return instructionIndex.get(mnemonic.toLowerCase());
}

export function getRegister(name: string): NasRegister | undefined {
    return registerIndex.get(name.toLowerCase());
}

export function getDirective(name: string): Directive | undefined {
    return directiveIndex.get(name.toLowerCase());
}

export function getInstructionCompletions(prefix: string): Instruction[] {
    const lower = prefix.toLowerCase();
    return instructions.filter((inst) => inst.mnemonic.startsWith(lower));
}

export function getRegisterCompletions(prefix: string): NasRegister[] {
    const lower = prefix.toLowerCase();
    return registers.filter((reg) => reg.name.startsWith(lower));
}

export function getDirectiveCompletions(prefix: string): Directive[] {
    const lower = prefix.toLowerCase();
    return directives.filter((dir) => dir.name.startsWith(lower));
}
